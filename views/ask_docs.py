import streamlit as st

from ignis import ui
from ignis.rag import (LLMUnavailable, NOT_FOUND, build_prompt, call_llm, llm_provider, load_index, search,
                       verify)

ui.page_header("Ask the NASA documents",
               "Search NASA's own reports. Every answer is grounded in numbered NASA passages shown below it.",
               "8 NASA technical reports (NTRS)")
chunks, bm25 = load_index()
question = st.text_input("Your question", "Why does a droplet flame go out at a large diameter?",
                         help="Searches FLEX, cool flames, BASS-II, Saffire IV-VI, SAME, ACME and the "
                              "partial-gravity white paper.")
hits = search(question, chunks, bm25, k=5) if question else []

provider = llm_provider()
c1, c2 = st.columns([1, 2.6], vertical_alignment="center")
clicked = c1.button("Generate cited answer", type="primary", disabled=not hits, icon=":material/auto_awesome:",
                    width="stretch")
c2.caption(f"SI layer: {provider} (only called when you click). The answer is AI-generated and checked against "
           "the passages." if provider else
           "No LLM key configured - retrieval-only mode. Add GEMINI_API_KEY or GROQ_API_KEY to Streamlit secrets.")

if clicked and hits:
    try:
        raw, model = call_llm(build_prompt(question, hits))
        kept, dropped = verify(raw, hits)
        st.session_state["ask_result"] = {"q": question, "kept": kept, "dropped": dropped, "model": model,
                                          "not_found": NOT_FOUND.lower() in raw.lower()}
    except LLMUnavailable as err:
        st.session_state["ask_result"] = {"q": question, "error": str(err)}

res = st.session_state.get("ask_result")
if res and res.get("q") == question:
    if res.get("error"):
        st.info(f"Could not generate an answer ({res['error']}). Showing the NASA passages only.")
    elif res["not_found"] and not res["kept"]:
        st.info("The model found no answer in these passages. Showing the NASA passages only.")
    elif not res["kept"]:
        st.warning("Every generated sentence failed the citation/number check, so nothing is shown. "
                   "Read the NASA passages below instead.")
    else:
        with st.container(border=True, key="ask_answer"):
            ui.section("Verified answer")
            st.markdown(res["kept"])
            st.caption(f"Generated by {res['model']} from the numbered passages below, then checked: each kept "
                       "sentence cites a passage and every number in it appears in that passage. AI-generated text.")
    if res.get("dropped"):
        with st.expander(f"{len(res['dropped'])} unsupported sentence(s) removed"):
            for s in res["dropped"]:
                st.write("- " + s)

if hits:
    ui.section("NASA source passages", f"top {len(hits)} matches")
for i, hit in enumerate(hits, start=1):
    with st.expander(f"[{i}] {hit['title']} - page {hit['page']} (match score {hit['score']:.1f})", expanded=i == 1):
        st.write(hit["text"])
        st.markdown(f"[Open source document]({hit['url']})")
if question and not hits:
    st.info("No matching passage. Try different keywords (e.g. 'extinction', 'cool flame', 'smoke detector').")
